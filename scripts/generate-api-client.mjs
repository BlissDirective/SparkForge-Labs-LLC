#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════
// generate-api-client — API-ENH OpenAPI 3.1 (Ultra)
// Phase 5 task #9 · Final-Audit_04-15-2026.md
// ════════════════════════════════════════════════════════════════
// Consumes the dev server's /api/docs JSON (or a local copy) and
// emits:
//   - src/lib/api/client.generated.ts     fetch client typed via the
//                                         OpenAPI paths/schemas
//   - src/lib/api/mocks.generated.ts      MSW handlers (one per path)
//
// This is a thin standalone generator that doesn't need a 3rd-party
// codegen CLI. Keeps the dependency surface tight. Output files are
// committed so the codegen step is optional at CI time (re-run only
// when the spec changes).
//
// Usage:
//   npm run api:gen
//   # or against a specific spec file:
//   node scripts/generate-api-client.mjs ./openapi-spec.json
// ════════════════════════════════════════════════════════════════

import { writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const SPEC_SOURCE = process.argv[2] || process.env.OPENAPI_SOURCE || 'http://localhost:3000/api/docs';
const OUT_DIR = path.join(ROOT, 'src', 'lib', 'api');

async function fetchSpec(source) {
  if (source.startsWith('http://') || source.startsWith('https://')) {
    const res = await fetch(source, { headers: { accept: 'application/json' } });
    if (!res.ok) throw new Error(`${source} → HTTP ${res.status}`);
    return res.json();
  }
  const { readFile } = await import('node:fs/promises');
  const raw = await readFile(source, 'utf8');
  return JSON.parse(raw);
}

function tsIdent(s) {
  return s.replace(/[^A-Za-z0-9_]/g, '_');
}

function pathToFnName(method, p) {
  const parts = p
    .split('/')
    .filter(Boolean)
    .map((part) =>
      part.startsWith('{') ? `By${tsIdent(part.slice(1, -1))}` : tsIdent(part),
    );
  return method.toLowerCase() + parts.map((x) => x[0].toUpperCase() + x.slice(1)).join('');
}

function jsonSchemaToTs(schema, components) {
  if (!schema) return 'unknown';
  if (schema.$ref) {
    const name = schema.$ref.split('/').pop();
    return tsIdent(name);
  }
  if (schema.oneOf) return schema.oneOf.map((s) => jsonSchemaToTs(s, components)).join(' | ');
  if (schema.anyOf) return schema.anyOf.map((s) => jsonSchemaToTs(s, components)).join(' | ');
  if (schema.enum) {
    return schema.enum.map((v) => (typeof v === 'string' ? JSON.stringify(v) : String(v))).join(' | ');
  }
  switch (schema.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      return `${jsonSchemaToTs(schema.items, components)}[]`;
    case 'object': {
      if (!schema.properties) return 'Record<string, unknown>';
      const required = new Set(schema.required || []);
      const lines = Object.entries(schema.properties).map(([k, v]) => {
        const opt = required.has(k) ? '' : '?';
        return `  ${JSON.stringify(k)}${opt}: ${jsonSchemaToTs(v, components)};`;
      });
      return `{\n${lines.join('\n')}\n}`;
    }
    default:
      return 'unknown';
  }
}

function renderClient(spec) {
  const components = spec.components?.schemas ?? {};
  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/generate-api-client.mjs — DO NOT EDIT.');
  lines.push('// Regenerate: npm run api:gen');
  lines.push('// Source: ' + SPEC_SOURCE);
  lines.push('');

  // Schema types.
  for (const [name, schema] of Object.entries(components)) {
    lines.push(`export type ${tsIdent(name)} = ${jsonSchemaToTs(schema, components)};`);
    lines.push('');
  }

  lines.push('export type RequestInit2 = Omit<RequestInit, "body"> & { signal?: AbortSignal };');
  lines.push('');
  lines.push('const BASE = (process.env.NEXT_PUBLIC_APP_URL || "").replace(/\\/$/, "");');
  lines.push('');
  lines.push('async function req<T>(method: string, url: string, body?: unknown, init?: RequestInit2): Promise<T> {');
  lines.push('  const res = await fetch(BASE + url, {');
  lines.push('    method,');
  lines.push('    credentials: "same-origin",');
  lines.push('    headers: body ? { "content-type": "application/json" } : undefined,');
  lines.push('    body: body !== undefined ? JSON.stringify(body) : undefined,');
  lines.push('    ...init,');
  lines.push('  });');
  lines.push('  const data = await res.json().catch(() => null);');
  lines.push('  if (!res.ok) throw Object.assign(new Error(data?.error || res.statusText), { status: res.status, data });');
  lines.push('  return data as T;');
  lines.push('}');
  lines.push('');

  // Path operations.
  for (const [p, ops] of Object.entries(spec.paths || {})) {
    for (const [method, op] of Object.entries(ops)) {
      if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue;
      const fnName = pathToFnName(method, p);
      const bodySchema =
        op.requestBody?.content?.['application/json']?.schema ?? null;
      const bodyTs = bodySchema ? jsonSchemaToTs(bodySchema, components) : null;
      const successResp = Object.entries(op.responses || {})
        .filter(([status]) => status.startsWith('2'))[0];
      const respSchema = successResp?.[1]?.content?.['application/json']?.schema;
      const respTs = respSchema ? jsonSchemaToTs(respSchema, components) : 'unknown';
      const args = bodyTs ? `body: ${bodyTs}, init?: RequestInit2` : `init?: RequestInit2`;
      const callArgs = bodyTs
        ? `"${method.toUpperCase()}", "${p}", body, init`
        : `"${method.toUpperCase()}", "${p}", undefined, init`;
      lines.push(`/** ${op.summary || ''} */`);
      lines.push(`export function ${fnName}(${args}): Promise<${respTs}> {`);
      lines.push(`  return req<${respTs}>(${callArgs});`);
      lines.push('}');
      lines.push('');
    }
  }

  return lines.join('\n');
}

function renderMsw(spec) {
  const lines = [];
  lines.push('// AUTO-GENERATED MSW handlers — DO NOT EDIT.');
  lines.push('// Regenerate: npm run api:gen');
  lines.push('');
  lines.push('import { http, HttpResponse } from "msw";');
  lines.push('');
  lines.push('export const apiHandlers = [');
  for (const [p, ops] of Object.entries(spec.paths || {})) {
    for (const method of Object.keys(ops)) {
      if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue;
      // MSW path params: {foo} → :foo
      const mswPath = p.replace(/\{([^}]+)\}/g, ':$1');
      lines.push(`  http.${method}("${mswPath}", () => {`);
      lines.push('    return HttpResponse.json({ success: true, data: {} });');
      lines.push('  }),');
    }
  }
  lines.push('];');
  return lines.join('\n');
}

async function main() {
  const spec = await fetchSpec(SPEC_SOURCE);
  await mkdir(OUT_DIR, { recursive: true });

  const clientTs = renderClient(spec);
  await writeFile(path.join(OUT_DIR, 'client.generated.ts'), clientTs + '\n', 'utf8');

  const mswTs = renderMsw(spec);
  await writeFile(path.join(OUT_DIR, 'mocks.generated.ts'), mswTs + '\n', 'utf8');

  console.log(
    `[generate-api-client] ${Object.keys(spec.paths || {}).length} paths, ` +
      `${Object.keys(spec.components?.schemas ?? {}).length} schemas. ` +
      `Wrote client.generated.ts + mocks.generated.ts.`,
  );
}

main().catch((err) => {
  console.error('[generate-api-client] failed:', err);
  process.exit(1);
});
