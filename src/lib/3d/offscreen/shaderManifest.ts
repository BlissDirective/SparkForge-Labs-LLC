// ════════════════════════════════════════════════════════════════
// shaderManifest — Phase 5 task #1 (§10.11) Ultra sub-module
// Worker-side shader precompile manifest
// ════════════════════════════════════════════════════════════════
// Problem: three.js r183 compiles GLSL shaders the first time a
// material is rendered. In a worker context this means the worker
// stalls mid-frame on first paint of every new material — visible
// as "shader compilation hitches" when the user enters a new scene.
//
// Solution: a manifest of shader programs the worker should compile
// before the first visible frame. The worker calls `renderer.compile
// (scene, camera)` against a placeholder scene assembled from the
// manifest on init.
//
// The manifest is static data, generated by hand here for the scenes
// that matter most (hero, cockpit shell, spatial dashboard). It can
// be regenerated automatically by scanning the built JS bundle (see
// scripts/generate-shader-manifest.mjs — future work).
//
// Design notes (Mythos §8.11 depth-wise LoRA analogy): treat each
// scene's shader set as a shared base + per-scene delta. We precompile
// the shared base once, then lazy-compile scene deltas as scenes become
// visible. Total warm-up cost is proportional to the base size, not
// the sum of scene sizes.
// ════════════════════════════════════════════════════════════════

export type ShaderManifestEntry = {
  /** Human-readable label for telemetry / debug. */
  id: string;
  /** Group — compiled together and kept resident. */
  group: 'core' | 'hero' | 'cockpit' | 'spatial' | 'game' | 'postfx';
  /** Material class from three.js — used to instantiate a probe. */
  materialClass:
    | 'MeshStandardMaterial'
    | 'MeshPhysicalMaterial'
    | 'MeshBasicMaterial'
    | 'ShaderMaterial'
    | 'LineBasicMaterial'
    | 'PointsMaterial'
    | 'SpriteMaterial';
  /**
   * Optional feature flags passed to the material constructor so the
   * compiled program matches runtime usage (e.g. transparent + skinning
   * yields a different program than opaque + static).
   */
  features?: {
    transparent?: boolean;
    fog?: boolean;
    skinning?: boolean;
    morphTargets?: boolean;
    instanced?: boolean;
    clipping?: boolean;
  };
  /** Optional lights required for correct compilation. */
  lights?: Array<'ambient' | 'directional' | 'point' | 'spot' | 'hemisphere'>;
  /**
   * Estimated compile cost (ms) on a mid-range laptop — used by
   * auto-quality to defer expensive programs when FPS is low.
   */
  estCostMs?: number;
};

