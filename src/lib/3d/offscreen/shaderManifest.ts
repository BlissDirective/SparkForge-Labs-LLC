/**
 * Get all entries for a group (stable order). Used by the worker on
 * init and when a new scene becomes visible.
 */
export function getManifestGroup(
  group: ShaderManifestEntry['group'],
): ShaderManifestEntry[] {
  return SHADER_MANIFEST.filter((e) => e.group === group);
}

/** Sum estimated compile cost for a set of groups. */
export function estimateGroupCostMs(groups: ShaderManifestEntry['group'][]): number {
  return SHADER_MANIFEST.filter((e) => groups.includes(e.group)).reduce(
    (acc, e) => acc + (e.estCostMs ?? 0),
    0,
  );
}

